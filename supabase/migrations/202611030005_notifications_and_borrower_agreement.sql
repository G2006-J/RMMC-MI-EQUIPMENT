create or replace function public.guard_borrower_agreement_version_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
begin
  if v_actor is not null then
    if not public.is_equipment_admin_user()
      or not exists (
        select 1 from public.profiles p
        where p.id = v_actor and p.role = 'admin' and p.account_status = 'active'
      ) then
      raise exception 'Only an administrator can change the active agreement version.';
    end if;
  elsif session_user not in ('postgres', 'supabase_admin') then
    raise exception 'A verified administrator is required to change an agreement version.';
  end if;

  if new.version_id is distinct from old.version_id
    or new.version_number is distinct from old.version_number
    or new.title is distinct from old.title
    or new.body_text is distinct from old.body_text
    or new.published_at is distinct from old.published_at
    or new.published_by is distinct from old.published_by then
    raise exception 'Published borrower agreement text is immutable; publish a new version instead.';
  end if;
  return new;
end;
$$;
revoke all on function public.guard_borrower_agreement_version_update() from public, anon, authenticated;
