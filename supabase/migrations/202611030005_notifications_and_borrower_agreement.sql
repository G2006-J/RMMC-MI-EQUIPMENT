create or replace function public.notify_damage_loss_report_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_borrower_user uuid;
begin
  if v_actor is not null and not public.is_equipment_manager_user() then
    raise exception 'Only equipment managers can change a damage or loss report.';
  elsif v_actor is null and session_user not in ('postgres', 'supabase_admin') then
    raise exception 'A verified equipment manager is required to change a damage or loss report.';
  end if;
  if tg_op = 'UPDATE' and new.resolution_status is not distinct from old.resolution_status then
    return new;
  end if;

  select br.user_id into v_borrower_user
  from public.borrowing_items bi
  join public.borrowings b using (borrowing_id)
  join public.borrowers br using (borrower_id)
  where bi.borrowing_item_id = new.borrowing_item_id;
  if v_borrower_user is null then
    raise exception 'The damage or loss report has no linked borrower.';
  end if;
  insert into public.notifications (user_id, borrowing_id, title, message, notification_type)
  values (
    v_borrower_user,
    (select bi.borrowing_id from public.borrowing_items bi
     where bi.borrowing_item_id = new.borrowing_item_id),
    'Damage or loss report updated',
    case when new.resolution_status in ('resolved', 'waived')
      then 'Staff updated the resolution of your damage or loss report.'
      else 'A damage or loss report was recorded for returned equipment.'
    end,
    'damage_report_updated'
  );
  return new;
end;
$$;
