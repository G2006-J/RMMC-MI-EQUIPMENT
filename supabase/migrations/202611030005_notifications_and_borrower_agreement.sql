create or replace function public.process_notification_schedule()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_created integer := 0;
  v_rows integer;
begin
  if v_actor is not null then
    if not public.is_equipment_admin_user() then
      raise exception 'Only administrators can run notification maintenance.';
    end if;
  elsif session_user not in ('postgres', 'supabase_admin') then
    raise exception 'Notification maintenance can run only from the trusted scheduler.';
  end if;

  perform pg_advisory_xact_lock(561991);

  insert into public.notifications (user_id, borrowing_id, title, message, notification_type)
  select br.user_id, b.borrowing_id, 'Equipment due within 24 hours',
    'Your released equipment is due within the next 24 hours. Please return it on time.',
    'due_soon'
  from public.borrowings b
  join public.borrowers br using (borrower_id)
  where b.transaction_status = 'released'
    and b.expected_return_date > now()
    and b.expected_return_date <= now() + interval '24 hours'
    and br.user_id is not null
    and not exists (
      select 1 from public.notifications n
      where n.user_id = br.user_id
        and n.borrowing_id = b.borrowing_id
        and n.notification_type = 'due_soon'
        and n.created_at >= current_date
        and n.created_at < current_date + interval '1 day'
    );
  get diagnostics v_rows = row_count;
  v_created := v_created + v_rows;

  insert into public.notifications (user_id, borrowing_id, title, message, notification_type)
  select br.user_id, b.borrowing_id, 'Equipment is overdue',
    'Your equipment return deadline has passed. Please contact equipment staff and arrange its return.',
    'item_overdue'
  from public.borrowings b
  join public.borrowers br using (borrower_id)
  where b.transaction_status = 'released'
    and b.expected_return_date < now()
    and br.user_id is not null
    and not exists (
      select 1 from public.notifications n
      where n.user_id = br.user_id
        and n.borrowing_id = b.borrowing_id
        and n.notification_type = 'item_overdue'
        and n.created_at >= current_date
        and n.created_at < current_date + interval '1 day'
    );
  get diagnostics v_rows = row_count;
  v_created := v_created + v_rows;

  delete from public.notifications
  where is_read and created_at < now() - interval '90 days';
  return v_created;
end;
$$;
revoke all on function public.process_notification_schedule() from public, anon, authenticated;

do $$
declare
  v_job_id bigint;
begin
  for v_job_id in
    select jobid from cron.job
    where jobname = 'borrower-notifications-and-retention'
  loop
    perform cron.unschedule(v_job_id);
  end loop;
  perform cron.schedule(
    'borrower-notifications-and-retention',
    '0 1 * * *',
    'select public.process_notification_schedule();'
  );
end;
$$;

