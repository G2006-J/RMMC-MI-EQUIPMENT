create trigger guard_borrower_agreement_version_update
before update on public.borrower_agreement_versions
for each row execute function public.guard_borrower_agreement_version_update();

create or replace function public.accept_borrower_agreement(p_version_id bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_acceptance_id bigint;
begin
  if v_actor is null or not public.is_verified_active_user()
    or not exists (
      select 1 from public.profiles p
      where p.id = v_actor and p.role = 'staff' and p.account_status = 'active'
    ) then
    raise exception 'Sign in with an active borrower account to accept the agreement.';
  end if;
  perform 1
  from public.borrower_agreement_versions v
  where v.version_id = p_version_id and v.active and v.published_at <= now()
  for share;
  if not found then
    raise exception 'This borrower agreement is no longer active. Review and accept the current version.';
  end if;

  insert into public.borrower_agreement_acceptances (user_id, version_id)
  values (v_actor, p_version_id)
  on conflict (user_id, version_id) do nothing
  returning acceptance_id into v_acceptance_id;
  if v_acceptance_id is null then
    select a.acceptance_id into v_acceptance_id
    from public.borrower_agreement_acceptances a
    where a.user_id = v_actor and a.version_id = p_version_id;
  end if;
  return v_acceptance_id;
end;
$$;
revoke all on function public.accept_borrower_agreement(bigint) from public, anon;
grant execute on function public.accept_borrower_agreement(bigint) to authenticated;

create or replace function public.publish_borrower_agreement(p_title text, p_body_text text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_previous jsonb;
  v_version_id bigint;
  v_version_number integer;
begin
  if v_actor is null or not public.is_equipment_admin_user()
    or not exists (
      select 1 from public.profiles p
      where p.id = v_actor and p.role = 'admin' and p.account_status = 'active'
    ) then
    raise exception 'Only an active administrator can publish a borrower agreement.';
  end if;
  perform pg_advisory_xact_lock(561992);
  if nullif(trim(p_title), '') is null or length(trim(p_title)) > 200
    or nullif(trim(p_body_text), '') is null or length(trim(p_body_text)) > 20000 then
    raise exception 'Provide an agreement title and body within the allowed lengths.';
  end if;

  select jsonb_build_object(
    'version_id', version_id,
    'version_number', version_number,
    'title', title,
    'body_text', body_text,
    'published_at', published_at
  ) into v_previous
  from public.borrower_agreement_versions
  where active
  for update;

  update public.borrower_agreement_versions
  set active = false
  where active;

  select coalesce(max(version_number), 0) + 1
  into v_version_number
  from public.borrower_agreement_versions;
  insert into public.borrower_agreement_versions (
    version_number, title, body_text, published_at, active, published_by
  )
  values (
    v_version_number, trim(p_title), trim(p_body_text), now(), true, v_actor
  )
  returning version_id into v_version_id;

  insert into public.borrower_agreement_audit_log (
    version_id, actor_id, action, before_values, after_values
  )
  values (
    v_version_id, v_actor, 'published', v_previous,
    jsonb_build_object(
      'version_id', v_version_id,
      'version_number', v_version_number,
      'title', trim(p_title),
      'body_text', trim(p_body_text)
    )
  );
  return v_version_id;
end;
$$;
revoke all on function public.publish_borrower_agreement(text, text) from public, anon;
grant execute on function public.publish_borrower_agreement(text, text) to authenticated;

create or replace function public.require_borrower_agreement_for_borrowing()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_current_version_id bigint;
begin
  if v_actor is null or not public.is_verified_active_user()
    or not exists (
      select 1 from public.profiles p
      where p.id = v_actor and p.role = 'staff' and p.account_status = 'active'
    ) then
    raise exception 'An active borrower account is required to submit a borrowing request.';
  end if;
  if not exists (
    select 1 from public.borrowers b
    where b.borrower_id = new.borrower_id
      and b.user_id = v_actor and b.status = 'active'
  ) then
    raise exception 'Borrowing requests must use your active borrower account.';
  end if;
  select v.version_id into v_current_version_id
  from public.borrower_agreement_versions v
  where v.active and v.published_at <= now()
  order by v.version_number desc
  limit 1
  for share;
  if v_current_version_id is null or not exists (
    select 1 from public.borrower_agreement_acceptances a
    where a.user_id = v_actor and a.version_id = v_current_version_id
  ) then
    raise exception 'Review and accept the current borrower agreement before submitting a request.';
  end if;
  return new;
end;
$$;
revoke all on function public.require_borrower_agreement_for_borrowing() from public, anon, authenticated;
drop trigger if exists require_borrower_agreement_for_borrowing on public.borrowings;
create trigger require_borrower_agreement_for_borrowing
before insert on public.borrowings
